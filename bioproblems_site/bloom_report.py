"""Describe observed corpus coverage without treating model probabilities as accuracy."""

import csv
import json
import collections
from pathlib import Path

import bioproblems_site.bloom as bloom
import bioproblems_site.bloom_rubric as rubric
import bioproblems_site.bloom_evidence as evidence
import bioproblems_site.problem_set_display as display


#============================================
def matrix(names: set[str], records: dict) -> list[str]:
	"""Count each filename once, with percentages among classified banks in this group."""
	counts = collections.Counter(bloom.pair(records[name]) for name in names if name in records)
	total = sum(counts.values())
	lines = [f"Classified: {total}; unavailable: {len(names) - total}.", "",
		"| Cognitive process | " + " | ".join(rubric.KNOWLEDGE) + " |",
		"| --- | --- | --- | --- | --- |"]
	for cognitive in rubric.COGNITIVE:
		cells = []
		for knowledge in rubric.KNOWLEDGE:
			count = counts[cognitive, knowledge]
			percent = 100 * count / total if total else 0
			cells.append(f"{count} ({percent:.1f}%)")
		lines.append("| " + " | ".join([cognitive, *cells]) + " |")
	return lines


#============================================
def write(root: Path) -> None:
	"""Publish compact matrices and a filename-level CSV for instructor exploration."""
	records = bloom.load(root)
	diagnostics = bloom.experiments(root)
	entries = evidence.entries(root)
	groups: dict[str, set[str]] = collections.defaultdict(set)
	placements: dict[str, set[str]] = collections.defaultdict(set)
	types = {}
	for entry in entries:
		name = entry.source_path.name
		type_code = display.question_type_for_source(entry.source_path)
		groups["Overall"].add(name)
		groups["Subject: " + entry.subject_title].add(name)
		groups["Question type: " + type_code].add(name)
		placements[name].add(entry.subject_title)
		types[name] = type_code
	lines = ["# Exploratory Bloom coverage", "",
		"Generated by `python3 -m devel.classify_bloom --action report`. Labels describe estimated dominant bank tasks.",
		"These counts are observations of classifier output, not measured educational accuracy.",
		"Each filename counts once overall and once within each subject where it appears.",
		"Subject groups overlap. Percentages use classified banks within each group; generated",
		"question quantities do not weight coverage. Zero means no banks were assigned to that cell.",
		"", "See [BLOOM_TAXONOMY_GUIDE.md](BLOOM_TAXONOMY_GUIDE.md) and",
		"[bloom_catalog.csv](bloom_catalog.csv) for filename-level results.", ""]
	versions = collections.Counter(diagnostics[name]["rubric_version"]
		for name in groups["Overall"] if name in diagnostics and name in records
		and bloom.pair(records[name]) == bloom.pair(diagnostics[name]))
	lines.extend([f"Rubric versions: {dict(versions)}.", ""])
	for group, names in groups.items():
		lines.extend(["## " + group, "", *matrix(names, records), ""])
	lines.extend(["## Cell examples", "",
		"Examples are filenames, not additional counts or reference labels.", ""])
	for cognitive in rubric.COGNITIVE:
		for knowledge in rubric.KNOWLEDGE:
			names = sorted(name for name in groups["Overall"] if name in records
				and bloom.pair(records[name]) == (cognitive, knowledge))
			if names:
				lines.append(f"- {cognitive} / {knowledge} ({len(names)}): `{'`, `'.join(names[:2])}`")
	baseline_path = root / "LOCAL_ONLY/bloom_baseline.json"
	if baseline_path.exists():
		baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
		changes = collections.Counter()
		for name in groups["Overall"] & baseline.keys() & records.keys():
			old_pair = tuple(baseline[name])
			new_pair = bloom.pair(records[name])
			if old_pair != new_pair:
				changes[" / ".join(old_pair) + " -> " + " / ".join(new_pair)] += 1
		lines.extend(["", "## Changes from baseline", "",
			f"{sum(changes.values())} banks changed their pair. This measures revision, not accuracy.", ""])
		lines.extend(f"- {transition}: {count}" for transition, count in changes.most_common())
	missing = sorted(groups["Overall"] - records.keys())
	if missing:
		lines.extend(["", "## Unavailable classifications", ""])
		lines.extend(f"- `{name}`" for name in missing)
	(root / "docs/BLOOM_COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
	with (root / "docs/bloom_catalog.csv").open("w", newline="", encoding="utf-8") as stream:
		writer = csv.writer(stream, lineterminator="\n")
		writer.writerow(["filename", "subjects", "question_type", "cognitive", "knowledge"])
		for name in sorted(groups["Overall"]):
			pair = bloom.pair(records[name]) if name in records else ("", "")
			values = [name, "; ".join(sorted(placements[name])), types[name], *pair]
			# ASVS 1.2.10: keep metadata from becoming spreadsheet formulas.
			writer.writerow(["'" + value if value.startswith(("=", "+", "-", "@"))
				else value for value in values])
